    fn fake_script(dir: &std::path::Path, name: &str, body: &str) -> std::path::PathBuf {
        let path = dir.join(name);
        std::fs::write(&path, body).expect("write fake script");
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))
                .expect("chmod fake script");
        }
        path
    }

    #[test]
    fn check_reports_ok_when_python_and_cuda_are_both_present() {
        let dir = tempfile::tempdir().expect("tempdir");
        let python = fake_script(
            dir.path(),
            "python3",
            "#!/bin/sh\necho 'Python 3.12.4'\nexit 0\n",
        );
        let nvidia_smi = fake_script(
            dir.path(),
            "nvidia-smi",
            "#!/bin/sh\necho 'NVIDIA GeForce RTX 4090, 24564 MiB'\nexit 0\n",
        );
        let report = check(
            python.to_str().expect("utf8 path"),
            nvidia_smi.to_str().expect("utf8 path"),
        );
        assert_eq!(report.worst(), Status::Ok);
        let python_check = report.items.iter().find(|c| c.name == "python").unwrap();
        assert_eq!(python_check.status, Status::Ok);
        assert!(python_check.message.contains("3.12.4"));
        let cuda_check = report.items.iter().find(|c| c.name == "cuda").unwrap();
        assert_eq!(cuda_check.status, Status::Ok);
        assert!(cuda_check.message.contains("RTX 4090"));
    }

    #[test]
    fn check_fails_closed_with_actionable_guidance_when_python_is_missing() {
        let dir = tempfile::tempdir().expect("tempdir");
        let nvidia_smi = fake_script(dir.path(), "nvidia-smi", "#!/bin/sh\nexit 0\n");
        let report = check(
            "codypendent-test-definitely-not-a-real-python",
            nvidia_smi.to_str().expect("utf8 path"),
        );
        let python_check = report.items.iter().find(|c| c.name == "python").unwrap();
        assert_eq!(python_check.status, Status::Fail);
        assert!(python_check.hint.as_deref().unwrap().contains("python.org"));
        assert_eq!(report.worst(), Status::Fail);
    }

    #[test]
    fn check_warns_not_fails_when_no_gpu_is_present() {
        // This is the honest, real state of the container that built this
        // scaffold: no GPU, no `nvidia-smi`. A missing GPU degrades the
        // report to a warning (fine-tuning needs a GPU, but the scaffold
        // itself — dataset editing, dry inspection — doesn't) rather than a
        // hard failure.
        let dir = tempfile::tempdir().expect("tempdir");
        let python = fake_script(
            dir.path(),
            "python3",
            "#!/bin/sh\necho 'Python 3.12.4'\nexit 0\n",
        );
        let report = check(
            python.to_str().expect("utf8 path"),
            "codypendent-test-definitely-not-a-real-nvidia-smi",
        );
        let cuda_check = report.items.iter().find(|c| c.name == "cuda").unwrap();
        assert_eq!(cuda_check.status, Status::Warn);
        assert!(cuda_check.message.contains("not found"));
        assert!(cuda_check
            .hint
            .as_deref()
            .unwrap()
            .to_lowercase()
            .contains("gpu"));
        assert_eq!(
            report.worst(),
            Status::Warn,
            "no GPU must warn, not fail, when python itself is fine"
        );
    }

    #[test]
    fn check_never_claims_a_gpu_is_present_when_nvidia_smi_reports_none() {
        let dir = tempfile::tempdir().expect("tempdir");
        let python = fake_script(
            dir.path(),
            "python3",
            "#!/bin/sh\necho 'Python 3.12.4'\nexit 0\n",
        );
        // nvidia-smi exists and exits 0 but prints nothing (a real shape:
        // the driver loaded but no device is attached).
        let nvidia_smi = fake_script(dir.path(), "nvidia-smi", "#!/bin/sh\nexit 0\n");
        let report = check(
            python.to_str().expect("utf8 path"),
            nvidia_smi.to_str().expect("utf8 path"),
        );
        let cuda_check = report.items.iter().find(|c| c.name == "cuda").unwrap();
        assert_eq!(cuda_check.status, Status::Warn);
        assert!(!cuda_check.message.to_lowercase().contains("detected: "));
    }

