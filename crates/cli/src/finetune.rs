//! `codypendent finetune` — scaffold an Unsloth QLoRA fine-tuning project
//! (`init`), verify the local Python/CUDA setup (`check`), and export the
//! repo's own session/eval history as training data (`dataset export`).
//!
//! Honesty note: this container has no GPU and no Python. `init` only writes
//! text files — it never installs a package or runs Python. `check` shells
//! out read-only to `python3 --version` / `nvidia-smi` (both injectable, so
//! tests mock them with fake scripts rather than depending on real ones) and
//! degrades to actionable guidance when either is missing, exactly as it
//! will in this container. Nothing here claims GPU/device-tested training
//! behavior — the generated `train.py` follows Unsloth's documented QLoRA
//! recipe, but it has not been run by this crate or its tests.
//!
//! `dataset export` is deferred (see [`dataset_export`]'s doc comment for the
//! precise reason) rather than shipped as a fragile, drifting
//! reimplementation of daemon-owned transcript reconstruction.

use std::path::PathBuf;
use std::process::Command;

use anyhow::Context;

use crate::doctor::{Check, Report, Status};

/// The Unsloth repo `finetune init` uses as the training base when
/// `--model` is omitted: a small, popular, pre-quantized-for-QLoRA repo
/// (verified live on the Hugging Face Hub while building this scaffold).
pub const DEFAULT_BASE_MODEL: &str = "unsloth/Qwen3-8B-unsloth-bnb-4bit";

/// The default scaffold directory (repository-relative) when `--out` is
/// omitted.
pub const DEFAULT_OUT_DIR: &str = "finetune";

/// `codypendent finetune init` options.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InitOptions {
    /// The Hugging Face repo `train.py` loads as its base model.
    pub base_model: String,
    /// The directory to scaffold into. Must not already exist (this is a
    /// `cargo new`-style scaffold, not a merge/overwrite).
    pub out_dir: PathBuf,
}

impl Default for InitOptions {
    fn default() -> Self {
        Self {
            base_model: DEFAULT_BASE_MODEL.to_string(),
            out_dir: PathBuf::from(DEFAULT_OUT_DIR),
        }
    }
}

/// What [`init`] wrote, for the CLI to report back.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InitReport {
    pub out_dir: PathBuf,
    pub files_written: Vec<PathBuf>,
}

/// Scaffold an Unsloth QLoRA fine-tuning project at `options.out_dir`:
/// pinned `requirements.txt`, a `train.py` for `options.base_model`, a
/// `dataset/train.jsonl` chat-transcript stub with its own format README,
/// and a top-level `README.md` covering GPU requirements, running the
/// script, GGUF export, and the `ollama create` step. Refuses (no I/O
/// performed) when `out_dir` already exists, so a re-run never silently
/// overwrites an in-progress project.
pub fn init(options: &InitOptions) -> anyhow::Result<InitReport> {
    if options.out_dir.exists() {
        anyhow::bail!(
            "{} already exists — choose a different --out, or remove it first",
            options.out_dir.display()
        );
    }
    let dataset_dir = options.out_dir.join("dataset");
    std::fs::create_dir_all(&dataset_dir)
        .with_context(|| format!("creating {}", dataset_dir.display()))?;

    let files: [(&str, String); 5] = [
        ("requirements.txt", requirements_txt().to_string()),
        ("README.md", readme_md(&options.base_model)),
        ("train.py", train_py(&options.base_model)),
        ("dataset/README.md", dataset_readme_md().to_string()),
        ("dataset/train.jsonl", dataset_train_jsonl().to_string()),
    ];
    let mut files_written = Vec::with_capacity(files.len());
    for (relative, contents) in &files {
        let path = options.out_dir.join(relative);
        std::fs::write(&path, contents).with_context(|| format!("writing {}", path.display()))?;
        files_written.push(path);
    }

    Ok(InitReport {
        out_dir: options.out_dir.clone(),
        files_written,
    })
}

