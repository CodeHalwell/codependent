const README_TEMPLATE: &str = r#####"# Unsloth QLoRA fine-tune: {{BASE_MODEL}}

Scaffolded by `codypendent finetune init`. This directory is a self-contained
Python project; Codypendent itself never installs or runs any of it -- these
commands are meant to be run by you, on a machine with an NVIDIA GPU.

## GPU requirements

Fine-tuning needs an NVIDIA GPU with CUDA support. 4-bit QLoRA keeps VRAM
requirements far below full fine-tuning, but you still need enough for the
base model's parameter count plus activations -- as a rough guide, budget at
least 8-12 GB of VRAM for a model in the 7-8B parameter range, more for a
larger base. Codypendent has not verified GPU behavior for this scaffold: the
environment that generated it has no GPU and does not install or run Python.
Run `codypendent finetune check` on the machine you intend to train on to
verify Python and CUDA are actually present there.

## Setup

```bash
pip install -r requirements.txt
```

## 1. Prepare your dataset

Edit `dataset/train.jsonl` -- one JSON object per line, each a chat transcript:

```json
{"messages": [{"role": "user", "content": "..."}, {"role": "assistant", "content": "..."}]}
```

See `dataset/README.md` for the exact format `train.py` expects.

## 2. Train

```bash
python train.py
```

This loads `{{BASE_MODEL}}` in 4-bit, attaches a LoRA adapter, and fine-tunes
on your dataset. The adapter is saved to `lora_model/` when training finishes.

## 3. Export to GGUF

Unsloth can merge the LoRA adapter and export straight to GGUF:

```python
from unsloth import FastLanguageModel

model, tokenizer = FastLanguageModel.from_pretrained("lora_model")
model.save_pretrained_gguf("gguf_model", tokenizer, quantization_method="q4_k_m")
```

This writes a `.gguf` file under `gguf_model/`. Pick a different
`quantization_method` (e.g. `q8_0`, `f16`) to trade size for fidelity.

## 4. Load it into Ollama

Write a `Modelfile` next to the exported GGUF:

```text
FROM ./gguf_model/<the-exported-file>.gguf
```

Then:

```bash
ollama create my-finetuned-model -f Modelfile
```

`my-finetuned-model` now appears in `ollama list`. Add it to Codypendent the
same way as any other local Ollama model: open the `/model` or `/provider`
picker in the TUI against the `ollama` provider, or add a `[[model]]` entry to
`models.toml` by hand with `model = "my-finetuned-model"`. Either way, run
`codypendent models bench <id>` afterward so the router has a measured
profile for it.
"#####;

fn readme_md(base_model: &str) -> String {
    README_TEMPLATE.replace("{{BASE_MODEL}}", base_model)
}

const TRAIN_PY_TEMPLATE: &str = r#####""""Unsloth QLoRA fine-tuning, scaffolded by `codypendent finetune init`.

Base model: {{BASE_MODEL}}

Requires a CUDA GPU (run `codypendent finetune check` to verify). See
README.md for setup, GGUF export, and the `ollama create` step.
"""

from datasets import load_dataset
from trl import SFTConfig, SFTTrainer
from unsloth import FastLanguageModel
from unsloth.chat_templates import get_chat_template

MAX_SEQ_LENGTH = 4096
BASE_MODEL = "{{BASE_MODEL}}"
DATASET_PATH = "dataset/train.jsonl"
OUTPUT_DIR = "outputs"
LORA_OUTPUT_DIR = "lora_model"


def load_model():
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=BASE_MODEL,
        max_seq_length=MAX_SEQ_LENGTH,
        load_in_4bit=True,
        dtype=None,  # auto-detect the best dtype for your GPU
    )
    model = FastLanguageModel.get_peft_model(
        model,
        r=16,
        lora_alpha=16,
        lora_dropout=0,
        target_modules=[
            "q_proj",
            "k_proj",
            "v_proj",
            "o_proj",
            "gate_proj",
            "up_proj",
            "down_proj",
        ],
        bias="none",
        use_gradient_checkpointing="unsloth",
        random_state=3407,
    )
    tokenizer = get_chat_template(tokenizer, chat_template="chatml")
    return model, tokenizer


def load_training_dataset(tokenizer):
    dataset = load_dataset("json", data_files=DATASET_PATH, split="train")

    def format_example(example):
        text = tokenizer.apply_chat_template(
            example["messages"], tokenize=False, add_generation_prompt=False
        )
        return {"text": text}

    return dataset.map(format_example)


def main():
    model, tokenizer = load_model()
    dataset = load_training_dataset(tokenizer)

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=dataset,
        dataset_text_field="text",
        max_seq_length=MAX_SEQ_LENGTH,
        args=SFTConfig(
            output_dir=OUTPUT_DIR,
            per_device_train_batch_size=2,
            gradient_accumulation_steps=4,
            warmup_steps=10,
            num_train_epochs=1,
            learning_rate=2e-4,
            logging_steps=1,
            optim="adamw_8bit",
            weight_decay=0.01,
            lr_scheduler_type="linear",
            seed=3407,
        ),
    )
    trainer.train()

    model.save_pretrained(LORA_OUTPUT_DIR)
    tokenizer.save_pretrained(LORA_OUTPUT_DIR)
    print(f"LoRA adapter saved to {LORA_OUTPUT_DIR}/")
    print("Next: export a GGUF (see README.md) and `ollama create` it.")


if __name__ == "__main__":
    main()
"#####;

fn train_py(base_model: &str) -> String {
    TRAIN_PY_TEMPLATE.replace("{{BASE_MODEL}}", base_model)
}

