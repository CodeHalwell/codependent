/// `codypendent finetune dataset export`: seed `dataset/train.jsonl` from the
/// repo's own session/eval history — DEFERRED, not stubbed-silent. Returns
/// the explanation (the CLI prints it and exits 0; nothing failed, the
/// feature is honestly incomplete).
///
/// Why no clean seam exists today, checked before writing this scaffold:
///
/// - **Session transcripts.** The daemon's own turn-reconstruction
///   (`session_transcript`/`continuation_prior` in
///   `crates/codypendentd/src/session_history.rs`) is `pub(crate)`-only
///   inside `codypendentd` — unreachable from `codypendent-cli` even though
///   `cli` depends on that crate (Rust visibility is not relaxed by a Cargo
///   dependency edge). No protocol `Command` exposes a reconstructed
///   transcript to a client either — only raw `SessionEvent`s via
///   `codypendent attach --events jsonl`, which would mean re-deriving that
///   same reconstruction here (streamed-delta coalescing, tool-result
///   summarizing, run compaction, …) as a second, drifting implementation of
///   daemon-owned logic — exactly the kind of duplicated-and-diverging code
///   path this project's own review process flags elsewhere.
/// - **Eval reports.** `codypendent-eval`'s `SuiteReport`/`CaseResult`/
///   `RunObservation` (`crates/eval/src/case.rs`) carry only structured
///   pass/fail/cost/duration signals — no raw model completion text — so
///   today's eval JSONL has no assistant-turn text to export either.
///
/// The clean fix is a protocol-level read command (e.g.
/// `ReadSessionTranscript`) backed by a small `pub` wrapper around the
/// existing `pub(crate)` reconstruction, so a client gets the SAME
/// transcript a continuation run already seeds itself with. That is a
/// daemon/protocol change — out of this vertical's ownership — so it is
/// filed as a follow-up rather than built here.
#[must_use]
pub fn dataset_export() -> String {
    "codypendent finetune dataset export: deferred.\n\n\
     No clean read-only seam exists yet for the CLI to export a reconstructed \
     chat transcript as fine-tuning data:\n\n\
     - Session transcripts: the daemon's own turn-reconstruction logic \
     (`session_transcript`/`continuation_prior` in \
     crates/codypendentd/src/session_history.rs) is `pub(crate)`-only inside \
     codypendentd, and no protocol Command exposes a reconstructed transcript \
     to a client -- only raw SessionEvents via `codypendent attach --events \
     jsonl`, which would mean re-deriving that same reconstruction here as a \
     second, drifting implementation of daemon-owned logic.\n\
     - Eval reports: codypendent-eval's SuiteReport/CaseResult/RunObservation \
     (crates/eval/src/case.rs) carry only structured pass/fail/cost/duration \
     signals -- no raw model completion text -- so today's eval JSONL has no \
     assistant-turn text to export either.\n\n\
     The clean fix is a protocol-level read command (e.g. ReadSessionTranscript) \
     backed by a small `pub` wrapper around the existing reconstruction -- a \
     daemon/protocol change, filed as a follow-up rather than built here.\n\n\
     In the meantime: hand-write examples into dataset/train.jsonl (see \
     dataset/README.md for the exact shape)."
        .to_string()
}

