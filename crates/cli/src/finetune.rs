/// Verify the local Python + CUDA setup for running the scaffolded
/// `train.py`, read-only. `python_bin`/`nvidia_smi_bin` are injected so
/// tests point them at fake scripts instead of depending on a real
/// interpreter or GPU driver (this container has neither). Mirrors
/// `codypendent doctor`'s `Report`/`Check`/`Status` shape (reused directly,
/// not duplicated) so the two checklists render identically.
#[must_use]
pub fn check(python_bin: &str, nvidia_smi_bin: &str) -> Report {
    let mut report = Report::default();
    check_python(&mut report, python_bin);
    check_cuda(&mut report, nvidia_smi_bin);
    report
}

fn check_python(report: &mut Report, python_bin: &str) {
    let check = match Command::new(python_bin).arg("--version").output() {
        Ok(output) if output.status.success() => {
            let mut version = String::from_utf8_lossy(&output.stdout).trim().to_string();
            if version.is_empty() {
                // Some interpreters print `--version` to stderr.
                version = String::from_utf8_lossy(&output.stderr).trim().to_string();
            }
            Check {
                name: "python".to_string(),
                status: Status::Ok,
                message: version,
                hint: None,
            }
        }
        Ok(output) => Check {
            name: "python".to_string(),
            status: Status::Fail,
            message: format!("`{python_bin} --version` exited with {}", output.status),
            hint: Some(
                "install Python 3.10+ (https://python.org) and ensure it is on PATH".to_string(),
            ),
        },
        Err(_) => Check {
            name: "python".to_string(),
            status: Status::Fail,
            message: format!("`{python_bin}` was not found on PATH"),
            hint: Some(
                "install Python 3.10+ (https://python.org) and ensure it is on PATH".to_string(),
            ),
        },
    };
    report.items.push(check);
}

fn check_cuda(report: &mut Report, nvidia_smi_bin: &str) {
    let check = match Command::new(nvidia_smi_bin)
        .args(["--query-gpu=name,memory.total", "--format=csv,noheader"])
        .output()
    {
        Ok(output) if output.status.success() => {
            let info = String::from_utf8_lossy(&output.stdout).trim().to_string();
            if info.is_empty() {
                Check {
                    name: "cuda".to_string(),
                    status: Status::Warn,
                    message: "nvidia-smi ran but reported no GPU".to_string(),
                    hint: Some(
                        "fine-tuning needs an NVIDIA GPU with CUDA; none detected here".to_string(),
                    ),
                }
            } else {
                Check {
                    name: "cuda".to_string(),
                    status: Status::Ok,
                    message: format!("GPU detected: {info}"),
                    hint: None,
                }
            }
        }
        Ok(output) => Check {
            name: "cuda".to_string(),
            status: Status::Warn,
            message: format!("`{nvidia_smi_bin}` exited with {}", output.status),
            hint: Some("fine-tuning needs an NVIDIA GPU with a working driver".to_string()),
        },
        Err(_) => Check {
            name: "cuda".to_string(),
            status: Status::Warn,
            message: format!("`{nvidia_smi_bin}` was not found on PATH"),
            hint: Some(
                "fine-tuning needs an NVIDIA GPU with CUDA installed; none detected in this \
                 environment"
                    .to_string(),
            ),
        },
    };
    report.items.push(check);
}

